"""Run Milwaukee bike trips and summarize what bike mode changes against the shortest route.

Run from the backend/ directory, with the server running (it needs the bike map):

    python -m app.bike_evaluate
    python -m app.bike_evaluate --profile family --url http://127.0.0.1:3143

Each trip goes through the same API the planner uses (POST /bike-route), and the recommended route
is compared with the shortest: minutes on busy streets (traffic stress 3 and 4), crossings of busy
roads without a signal, places where a cyclist was killed, railroad tracks, the safety score, and
the extra minutes it takes. Writes BIKE_RESULTS.md at the repo root and data/bike-results.csv.
Costs nothing: bike routes use no paid requests.
"""

